# bot/ai/models.py
"""Выбор AI-моделей Cloudflare Workers AI.

Каждый агент использует свою модель:
  - 70B (llama-3.3-70b-instruct-fp8-fast) — для задач, требующих глубокого
    понимания контекста, логики и генерации качественного текста.
  - 8B  (llama-3.1-8b-instruct) — для структурированного анализа по
    готовым данным, где большая модель избыточна.
"""

# Python 3.10 не имеет StrEnum (появился в 3.11).
# Используем простые строковые константы.

LLAMA_70B  = "@cf/meta/llama-3.3-70b-instruct-fp8-fast"
LLAMA_8B   = "@cf/meta/llama-3.1-8b-instruct"
MISTRAL_7B = "@cf/mistral/mistral-7b-instruct-v0.2"

# ── Модели по агентам ─────────────────────────────────────────────────────────

# 🤖 Interview AI — генерирует живые вопросы, понимает контекст всей анкеты.
# Требует мощной модели для естественного диалога.
INTERVIEW_MODEL = LLAMA_70B

# 📄 Resume Builder — структурирует и формулирует итоговое резюме кандидата.
# Требует качественной генерации текста.
RESUME_MODEL = LLAMA_70B

# 🎯 Skill Analyzer — сопоставляет навыки кандидата с перечнем.
# Аналитика по готовым данным, 8B достаточно.
SKILL_ANALYZER_MODEL = LLAMA_8B

# 🤝 Communication Analyzer — оценивает стиль общения по ответам интервью.
# Средняя задача, 8B справляется.
COMMUNICATION_MODEL = LLAMA_8B

# ⚠️ Integrity AI (Fraud / Red Flag Detector) — ищет противоречия между
# анкетой и ответами интервью. Требует сильной логики → 70B.
INTEGRITY_MODEL = LLAMA_70B

# 💼 Job Matcher — сравнивает профиль кандидата с требованиями вакансии.
# Структурированное сравнение, 8B достаточно.
JOB_MATCHER_MODEL = LLAMA_8B

# 📋 HR Summary — формирует итоговый отчёт для HR-менеджера.
# Должен быть качественным и убедительным → 70B.
HR_SUMMARY_MODEL = LLAMA_70B

# ── Устаревший алиас (оставлен для обратной совместимости) ───────────────────
# Используется в bot/ai/resume.py. Не использовать в новом коде.
SCREENING_MODEL = LLAMA_70B
